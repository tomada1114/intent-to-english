"""The migrations build exactly the schema ``tables.py`` declares, and undo it.

Plain ``def`` tests: ``migrations/env.py`` runs ``asyncio.run``, which cannot
start inside the event loop an async test runs on.
"""

from __future__ import annotations

import asyncio
from contextlib import contextmanager
from typing import TYPE_CHECKING

import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import Column, Integer, Table, create_engine, inspect, make_url

from intent_to_english.adapters.sql.call_log import read_calls
from intent_to_english.adapters.sql.tables import metadata

if TYPE_CHECKING:
    from collections.abc import Iterator

    from sqlalchemy import Inspector


@contextmanager
def _inspect(url: str) -> Iterator[Inspector]:
    # A blocking engine on the same file: these tests run outside any loop.
    engine = create_engine(make_url(url).set(drivername="sqlite"))
    try:
        with engine.connect() as connection:
            yield inspect(connection)
    finally:
        engine.dispose()


APP_TABLES = {"sessions", "timeline_entries", "submissions", "model_calls"}
CURRENT_TABLES = {*APP_TABLES, "submission_cancellations"}
TODOS_REVISION = "f58f944d0d8e"
SESSIONS_REVISION = "de3f10d569ec"


def _todos_shape(inspector: Inspector) -> tuple[object, ...]:
    columns = [
        (column["name"], str(column["type"]), column["nullable"])
        for column in inspector.get_columns("todos")
    ]
    return (columns, inspector.get_pk_constraint("todos"))


def test_upgrade_head_matches_metadata(alembic_config, sqlite_url):
    command.upgrade(alembic_config, "head")

    # Raises AutogenerateDiffsDetected if a revision would hold any operation.
    command.check(alembic_config)
    with _inspect(sqlite_url) as inspector:
        assert set(inspector.get_table_names()) == {"alembic_version", *metadata.tables}


def test_upgrade_head_leaves_only_the_session_tables(alembic_config, sqlite_url):
    command.upgrade(alembic_config, "head")

    with _inspect(sqlite_url) as inspector:
        assert set(inspector.get_table_names()) == {"alembic_version", *CURRENT_TABLES}


def test_downgrade_to_session_revision_recreates_todos_as_its_revision_made_it(
    alembic_config, sqlite_url
):
    command.upgrade(alembic_config, SESSIONS_REVISION)
    with _inspect(sqlite_url) as inspector:
        before = _todos_shape(inspector)
    command.upgrade(alembic_config, "head")

    command.downgrade(alembic_config, SESSIONS_REVISION)

    with _inspect(sqlite_url) as inspector:
        assert set(inspector.get_table_names()) == {
            "alembic_version",
            "todos",
            *APP_TABLES,
        }
        assert _todos_shape(inspector) == before
    columns, primary_key = before
    assert columns == [
        ("id", "CHAR(32)", False),
        ("title", "VARCHAR(200)", False),
        ("is_completed", "BOOLEAN", False),
        ("created_at", "DATETIME", False),
    ]
    assert primary_key == {"constrained_columns": ["id"], "name": "pk_todos"}


def test_check_table_missing_from_migrations_raises_naming_it(alembic_config):
    command.upgrade(alembic_config, "head")
    unmigrated = Table("unmigrated", metadata, Column("id", Integer, primary_key=True))
    try:
        with pytest.raises(AutogenerateDiffsDetected, match=r"unmigrated"):
            command.check(alembic_config)
    finally:
        metadata.remove(unmigrated)


def test_downgrade_base_leaves_only_the_version_table(alembic_config, sqlite_url):
    command.upgrade(alembic_config, "head")

    command.downgrade(alembic_config, "base")

    with _inspect(sqlite_url) as inspector:
        assert set(inspector.get_table_names()) == {"alembic_version"}


def test_downgrade_to_first_revision_keeps_only_todos(alembic_config, sqlite_url):
    command.upgrade(alembic_config, "head")
    command.downgrade(alembic_config, TODOS_REVISION)
    with _inspect(sqlite_url) as inspector:
        assert set(inspector.get_table_names()) == {"alembic_version", "todos"}


def test_upgrade_without_database_url_raises_naming_the_variable(
    alembic_config, monkeypatch
):
    monkeypatch.delenv("INTENT_TO_ENGLISH_DATABASE_URL")

    with pytest.raises(
        RuntimeError, match=r"^INTENT_TO_ENGLISH_DATABASE_URL must be set"
    ):
        command.upgrade(alembic_config, "head")


def test_http_status_migration_is_nullable_and_preserves_existing_calls(
    alembic_config, sqlite_url, seed_call_log
):
    command.upgrade(alembic_config, "head")
    with _inspect(sqlite_url) as inspector:
        columns = {
            column["name"]: column for column in inspector.get_columns("model_calls")
        }
        assert columns["status"]["nullable"] is True
        assert str(columns["status"]["type"]) == "INTEGER"
    records = asyncio.run(seed_call_log(sqlite_url))

    command.downgrade(alembic_config, "a41f21f8e037")
    with _inspect(sqlite_url) as inspector:
        assert "status" not in {
            column["name"] for column in inspector.get_columns("model_calls")
        }
    command.upgrade(alembic_config, "head")

    restored = asyncio.run(read_calls(sqlite_url))
    assert restored == tuple(
        sorted(records, key=lambda record: (record.created_at, record.id))
    )
    assert all(record.call.status is None for record in restored)
